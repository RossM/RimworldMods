using System.Linq;
using System.Threading.Tasks;
using NUnit.Framework;

namespace Xylib.Analyzer.Tests;

public sealed class PatchChecksTests
{
    [Test]
    public async Task ReportsNonStaticDisharmonyClass()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("[Disharmony.Patch] class Patch { }");
        Assert.That(diagnostics.Select(d => (d.Id, d.Descriptor.Category)), Is.EqualTo(new[] { ("XYLIB0001", "Style") }));
    }

    [TestCase("Prefix")]
    [TestCase("Postfix")]
    [TestCase("Target")]
    [TestCase("Targets")]
    public async Task PatchMethodNeedsFeature(string attribute)
    {
        var diagnostics = await AnalyzerTestHelper.Analyze($$"""
            [Disharmony.Patch] static class Patch
            {
                [Disharmony.{{attribute}}] public static void {{attribute}}() { }
            }
            """);
        Assert.That(diagnostics.Select(d => d.Id), Is.EqualTo(new[] { "XYLIB0002" }));
    }

    [Test]
    public async Task FeatureOnHelperIsReported()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            [Disharmony.Patch] static class Patch
            {
                [Xylib.Feature] public static void Helper() { }
            }
            """);
        Assert.That(diagnostics.Select(d => d.Id), Is.EqualTo(new[] { "XYLIB0003" }));
    }

    [TestCase("Prefix", "Before", "XYLIB0004")]
    [TestCase("Postfix", "After", "XYLIB0005")]
    public async Task ReportsWrongPatchName(string attribute, string name, string id)
    {
        var diagnostics = await AnalyzerTestHelper.Analyze($$"""
            [Disharmony.Patch] static class Patch
            {
                [Disharmony.{{attribute}}, Xylib.Feature] public static void {{name}}() { }
            }
            """);
        Assert.That(diagnostics.Select(d => d.Id), Is.EqualTo(new[] { id }));
        Assert.That(diagnostics.Single().Location.SourceTree!.GetText().ToString(diagnostics.Single().Location.SourceSpan), Is.EqualTo(name));
    }

    [TestCase("Prefix", "Prefix")]
    [TestCase("Prefix", "Work_Prefix")]
    [TestCase("Postfix", "Postfix")]
    [TestCase("Postfix", "Work_Postfix")]
    public async Task AcceptsPatchNames(string attribute, string name)
    {
        var diagnostics = await AnalyzerTestHelper.Analyze($$"""
            [Disharmony.Patch] static class Patch
            {
                [Disharmony.{{attribute}}, Xylib.Feature] public static void {{name}}() { }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task DoesNotCheckHarmonyPatches()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            [HarmonyLib.HarmonyPatch] class Patch
            {
                [HarmonyLib.HarmonyPrefix] public static void Before() { }
                [HarmonyLib.HarmonyPostfix] public static void After(int __result) { }
                [HarmonyLib.HarmonyTranspiler] public static void Rewrite() { }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task DoesNotRequireRefResultForDisharmonyPostfix()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            [Disharmony.Patch] static class Patch
            {
                [Disharmony.Postfix, Xylib.Feature] public static void Postfix(int __result) { }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task UsesInheritedMethodAttributes()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            class Parent
            {
                [Disharmony.Prefix, Xylib.Feature] public virtual void Before() { }
            }
            [Disharmony.Patch] class Child : Parent
            {
                public override void Before() { }
            }
            """);
        Assert.That(diagnostics.Select(d => d.Id), Is.EquivalentTo(new[] { "XYLIB0001", "XYLIB0004" }));
    }

    [Test]
    public async Task IgnoresUnrelatedAttributesWithSameName()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            class PatchAttribute : System.Attribute { }
            class PrefixAttribute : System.Attribute { }
            [Patch] class Container { [Prefix] public void Before() { } }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task RunsWithoutFrameworkReferences()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("class Ordinary { public int value; }", contracts: "");
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task DoesNotAnalyzeGeneratedCode()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            // <auto-generated/>
            [Disharmony.Patch] class Container
            {
                [Disharmony.Prefix] public void Before() { }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task DoesNotInheritNonInheritedFeatureAttributes()
    {
        var contracts = AnalyzerTestHelper.Contracts.Replace(
            "System.AttributeTargets.Method, AllowMultiple = true", "System.AttributeTargets.Method, AllowMultiple = true, Inherited = false");
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            class Parent
            {
                [Disharmony.Prefix, Xylib.Feature] public virtual void Prefix() { }
            }
            [Disharmony.Patch] class Child : Parent
            {
                public override void Prefix() { }
            }
            """, contracts);
        Assert.That(diagnostics.Select(d => d.Id), Is.EquivalentTo(new[] { "XYLIB0001", "XYLIB0002" }));
    }
}
