    [Test]
    public async Task AllowsLocalSuppressionInHelperImplementations()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            static class Helpers
            {
                extension(Verse.GeneDef gene)
                {
                    public Xylib.DefModExtension_GeneWithComps Extension_GeneWithComps
                    {
                        get
                        {
            #pragma warning disable XYLIB0011
                            return gene.GetModExtension<Xylib.DefModExtension_GeneWithComps>();
            #pragma warning restore XYLIB0011
                        }
                    }
                }
                extension(Verse.Pawn pawn)
                {
            #pragma warning disable XYLIB0012
                    public bool HasActiveGene(Verse.GeneDef gene) => pawn.genes.HasActiveGene(gene);
            #pragma warning restore XYLIB0012
                }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task RestoresWarningsAfterLocalSuppressions()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            class Example
            {
                public void Run(Verse.Pawn pawn, Verse.GeneDef gene)
                {
            #pragma warning disable XYLIB0011, XYLIB0012
                    gene.GetModExtension<Xylib.DefModExtension_GeneWithComps>();
                    pawn.genes.HasActiveGene(gene);
            #pragma warning restore XYLIB0011, XYLIB0012
                    gene.GetModExtension<Xylib.DefModExtension_GeneWithComps>();
                    pawn.genes.HasActiveGene(gene);
                }
            }
            """);
        Assert.That(diagnostics.Select(d => d.Id), Is.EquivalentTo(new[] { "XYLIB0011", "XYLIB0012" }));
    }

