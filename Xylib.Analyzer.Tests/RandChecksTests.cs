using System.Linq;
using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using NUnit.Framework;

namespace Xylib.Analyzer.Tests;

public sealed class RandChecksTests
{
    [TestCase("using Verse;", "Rand.PushState(123)")]
    [TestCase("", "global::Verse.Rand.PushState(123)")]
    [TestCase("using Random = Verse.Rand;", "Random.PushState(123)")]
    [TestCase("using static Verse.Rand;", "PushState(123)")]
    [TestCase("using Verse;", "Rand.PushState(seed: 123)")]
    [TestCase("using Verse;", "Rand.PushState((short)123)")]
    public async Task ReportsSeededPushState(string imports, string call)
    {
        var diagnostics = await AnalyzerTestHelper.Analyze($$"""
            {{imports}}
            class Example
            {
                public void Run() { {{call}}; }
            }
            """);
        Assert.That(diagnostics.Select(d => d.Id), Is.EqualTo(new[] { "XYLIB0010" }));
        var diagnostic = diagnostics.Single();
        Assert.That(diagnostic.Severity, Is.EqualTo(DiagnosticSeverity.Warning));
        Assert.That(diagnostic.Descriptor.Category, Is.EqualTo("Correctness"));
        Assert.That(diagnostic.GetMessage(), Is.EqualTo("Use RandBlock instead of calling Rand.PushState(int) directly"));
        Assert.That(diagnostic.Location.SourceTree!.GetText().ToString(diagnostic.Location.SourceSpan), Is.EqualTo(call));
    }

    [Test]
    public async Task AllowsParameterlessPushState()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            class Example
            {
                public void Run() { Verse.Rand.PushState(); }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task AllowsRandBlock()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            class Example
            {
                public void Run() { using var random = new Verse.RandBlock(123); }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task IgnoresUnrelatedRandType()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            static class Rand
            {
                public static void PushState(int seed) { }
            }
            class Example
            {
                public void Run() { Rand.PushState(123); }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task IgnoresOtherPushStateOverloads()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            class Example
            {
                public void Run()
                {
                    Verse.Rand.PushState(123L);
                    Verse.Rand.PushState<int>(123);
                    int seed = 123;
                    Verse.Rand.PushState(ref seed);
                }
            }
            """, contracts: """
            namespace Verse
            {
                public static class Rand
                {
                    public static void PushState(int seed) { }
                    public static void PushState(long seed) { }
                    public static void PushState<T>(int seed) { }
                    public static void PushState(ref int seed) { }
                }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task RunsWithoutVerseRand()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            static class Rand
            {
                public static void PushState(int seed) { }
            }
            class Example
            {
                public void Run() { Rand.PushState(123); }
            }
            """, contracts: "");
        Assert.That(diagnostics, Is.Empty);
    }

    [Test]
    public async Task IgnoresGeneratedCode()
    {
        var diagnostics = await AnalyzerTestHelper.Analyze("""
            // <auto-generated/>
            class Example
            {
                public void Run() { Verse.Rand.PushState(123); }
            }
            """);
        Assert.That(diagnostics, Is.Empty);
    }
}
